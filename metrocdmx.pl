% camino

no_llego(Inicio,Fin):- (Inicio \== Fin). 

ruta(Fin, Fin, Visitados, Visitados).

ruta(Inicio, Fin, Visitados, Resultado) :-
    no_llego(Inicio, Fin),
    conexion(Inicio, Siguiente, _, _),
    \+ member(Siguiente, Visitados),
    ruta(Siguiente, Fin, [Siguiente | Visitados], Resultado).


% costo de viaje
ruta_costos(Fin, Fin, Visitados, Visitados, Total, Total).
ruta_costos(Inicio, Fin, Visitados, Resultados, Acum, Total) :-
    no_llego(Inicio, Fin), 
    conexion(Inicio, Siguiente, _, P),
    \+ member(Siguiente, Visitados), 
    NuevoAcum is Acum + P, 
    ruta_costos(Siguiente, Fin, [Siguiente | Visitados], Resultados, NuevoAcum, Total). 

% costo de transbordos

transbor(LineaInicial, LineaFinal, 2) :- (LineaInicial \== LineaFinal). 
transbor(LineaInicial, LineaFinal, 0) :- (LineaInicial == LineaFinal).

% Ruta final 

ruta_final(Fin, Fin, Visitados, Visitados, _ , Total, Total).
ruta_final(Inicio, Fin, Visitados, Resultados, LineaAct, Acum, Total) :-
    no_llego(Inicio, Fin), 
    conexion(Inicio, Siguiente, L, P),
    \+ member(Siguiente, Visitados), 
    transbor(LineaAct, L, Extra),
    NuevoAcum is Acum + (P + Extra), 
    ruta_final(Siguiente, Fin, [Siguiente | Visitados], Resultados, L, NuevoAcum, Total). 


